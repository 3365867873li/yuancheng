function [f, g] = engineering_eval(name, x)
% 计算三个工程问题的目标函数值 f 与约束向量 g
% 约束约定：g <= 0 表示满足约束，g > 0 表示违反约束

switch lower(name)

    % ==================== 问题1：拉伸/压缩弹簧设计 ====================
    case 'spring'
        x1 = x(1); x2 = x(2); x3 = x(3);        % x1=线径d, x2=平均圈径D, x3=有效圈数N
        f = (x3 + 2) * x2 * x1^2;               % 目标：最小化弹簧重量
        g = zeros(1, 4);                        % 共 4 个约束
        g(1) = 1 - (x2^3 * x3) / (71785 * x1^4);                         % 剪切应力约束
        g(2) = (4*x2^2 - x1*x2) / (12566 * (x2*x1^3 - x1^4)) + 1/(5108*x1^2)-1; % 挠度约束
        g(3) = 1 - 140.45 * x1 / (x2^2 * x3);                            % 振动频率约束
        g(4) = (x1 + x2) / 1.5 - 1;                                      % 外径约束

    % ==================== 问题2：焊接梁设计 ====================
    case 'welded'
        x1 = x(1); x2 = x(2); x3 = x(3); x4 = x(4); % x1=焊高h, x2=焊长l, x3=梁高t, x4=梁厚b
        P = 6000; L = 14; E = 30e6; G = 12e6;   % 载荷、梁长、弹性模量、剪切模量
        tau_max = 13600; sigma_max = 30000; delta_max = 0.25; % 各许用值
        f = 1.10471*x1^2*x2 + 0.04811*x3*x4*(14 + x2); % 目标：最小化制造成本
        tau1 = P / (sqrt(2)*x1*x2);             % 主剪应力
        M = P * (L + x2/2);                     % 弯矩
        R = sqrt(x2^2/4 + ((x1 + x3)/2)^2);     % 合成力作用点极半径
        J = 2 * (sqrt(2)*x1*x2 * (x2^2/12 + ((x1 + x3)/2)^2)); % 极惯性矩
        tau2 = M*R/J;                           % 次剪应力
        tau = sqrt(tau1^2 + 2*tau1*tau2*(x2/(2*R)) + tau2^2);   % 合成剪应力
        sigma = 6*P*L / (x4*x3^2);              % 弯曲正应力
        delta = 4*P*L^3 / (E*x4*x3^3);          % 梁端挠度
        Pc = (4.013*E*sqrt(x3^2*x4^6/36)/L^2) * (1 - (x3/(2*L))*sqrt(E/(4*G))); % 屈曲载荷
        g = zeros(1, 7);                        % 共 7 个约束
        g(1) = tau - tau_max;                   % 剪应力约束
        g(2) = sigma - sigma_max;               % 正应力约束
        g(3) = delta - delta_max;               % 挠度约束
        g(4) = x1 - x4;                         % 焊高与梁厚关系约束
        g(5) = P - Pc;                          % 屈曲载荷约束
        g(6) = 0.125 - x1;                      % 焊高下限约束
        g(7) = 0.10471*x1^2 + 0.04811*x3*x4*(14 + x2) - 5; % 成本上限约束

    % ==================== 问题3：压力容器设计 ====================
    case 'vessel'
        x1 = x(1); x2 = x(2); x3 = x(3); x4 = x(4); % x1=壳厚Ts, x2=封头厚Th, x3=内径R, x4=筒长L
        f = 0.6224*x1*x3*x4 + 1.7781*x2*x3^2 + 3.1661*x1^2*x4 + 19.84*x1^2*x3; % 目标：最小化总成本
        g = zeros(1, 4);                        % 共 4 个约束
        g(1) = -x1 + 0.0193*x3;                 % 壳厚度约束
        g(2) = -x2 + 0.00954*x3;                % 封头厚度约束
        g(3) = -pi*x3^2*x4 - (4/3)*pi*x3^3 + 1296000; % 容积约束
        g(4) = x4 - 240;                        % 筒长约束

    otherwise
        error('未知的工程问题：%s', name);
end
end