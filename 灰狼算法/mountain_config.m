function cfg = mountain_config()
% ============================================================
% 三维山地航路规划 —— 场景与指标配置
% 依据：李国帅 等《基于改进灰狼优化算法的无人飞行器山地航路规划》
%       （电光与控制，2019，56(8)）
%
% 说明：论文中的若干常数（k_m、k_l 等）在 PDF 文本提取中存在字形错位，
%       本文件集中列出并加了标注，请对照原文核对后修改。
% ============================================================

%% ---------- 1. 规划空间与起终点 ----------
cfg.S = [200, 200, 400];        % 起点 [x, y, z] / m
cfg.T = [4800, 4600, 300];      % 终点 [x, y, z] / m
cfg.n = 8;                      % 中间航路点个数 → 总航路点数 N_p = n+2

%% ---------- 2. 三维山地地形（高斯峰体叠加，对应论文 1.1 节栅格环境） ----------
% 每行一个峰体：[峰心x, 峰心y, 峰高h, 展布σ]，单位 m
cfg.peaks = [ ...
     900, 1200,  900, 700;
    1900,  700, 1100, 650;
    2600, 2100, 1300, 800;
    1500, 3000,  950, 700;
    3300, 3400, 1150, 750;
    4100, 1500,  850, 600];

%% ---------- 3. 决策变量范围 ----------
cfg.y_range = [-500, 5500];     % 航路点 y 坐标范围 / m
cfg.z_range = [0, 1600];        % 航路点高度范围 / m
% x 方向：把 S→T 的 x 跨度均分为 n+1 段，第 i 个航路点的 x 锁在第 i 段内，
%         从而保证航路不折返（论文中由最短航路点间隔约束间接保证）

%% ---------- 4. 工程约束（论文 1.1.2 节，式(1)~(5)） ----------
cfg.S_max     = 9000;           % 最大航程约束 / m             式(1)
cfg.theta_max = 70;             % 航线最大夹角约束 / 度         式(3)
cfg.d_min     = 300;            % 最短航路点间隔约束 / m        式(4)
cfg.d_max     = 1800;           % 最长航路点间隔约束 / m        式(4)
cfg.h_safe    = 50;             % 最低离地安全余量 / m          式(5)
cfg.h_max     = 1600;           % 最大飞行高度 / m              式(5)
cfg.h_ctrl    = 1500;           % 隐蔽性控制高度（式(6)中的 1500） / m

%% ---------- 5. 指标调节系数（论文 1.3 节） ----------
cfg.k_r = 1.0;                  % 隐蔽性调节系数，论文取 1.0
cfg.k_m = 0.12;                 % 机动性调节系数【待核对原文】
cfg.k_l = 0.00015;              % 航程调节系数（使 K_l 保持个位数）【待核对原文】

%% ---------- 6. 四项指标权重 [隐蔽, 机动, 安全, 航程]（论文式(12)） ----------
cfg.eta = [0.25, 0.25, 0.25, 0.25];

%% ---------- 7. 指标计算与罚函数 ----------
cfg.samples_per_seg = 15;       % 每段航路的采样点数（沿航路积分）
cfg.PENALTY = 200;              % 约束违反罚系数（把约束问题转为无约束）

%% ---------- 8. 免疫克隆变异算子参数（论文 2.2 节） ----------
cfg.immu.Nc   = 6;              % 每个领导狼(α/β/δ)的克隆规模
cfg.immu.pm   = 0.25;           % 逐维变异概率
cfg.immu.sigma = 0.08;          % 变异步长系数（相对变量范围）
cfg.immu.eps  = 1e-3;           % 触发阈值 ε（式(16)）
cfg.immu.gap  = 3;              % 触发判断的代数间隔（式(16)中为 3）

end
